// Isolated PostgreSQL/WASM integration test. No application connection string is read.
// npm install --prefix tmp/storage-sql-test --no-save --package-lock=false @electric-sql/pglite@0.3.14
// node tools/tenant-storage-check/check.mjs
import { PGlite } from "../../tmp/storage-sql-test/node_modules/@electric-sql/pglite/dist/index.js";
import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";

const db = new PGlite();
const a = "10000000-0000-0000-0000-000000000001";
const b = "10000000-0000-0000-0000-000000000002";
const root = "00000000-0000-0000-0000-000000000001";
const plan = "20000000-0000-0000-0000-000000000001";
const migration = await readFile(new URL("../../backend/Mahima.Api.v3.clean/Sql/20260918_tenant_storage.sql", import.meta.url), "utf8");
const scalar = async (sql, params = []) => Object.values((await db.query(sql, params)).rows[0])[0];
const used = async (tenant = a) => Number(await scalar("SELECT database_bytes FROM tenant_storage_usage WHERE tenant_id=$1", [tenant]));
let checks = 0;
const check = (condition, message) => { assert.ok(condition, message); checks++; };
await db.exec(`
  CREATE TABLE tenants(id uuid PRIMARY KEY,is_root_tenant boolean NOT NULL DEFAULT false);
  CREATE TABLE tenant_subscriptions(id uuid PRIMARY KEY,tenant_id uuid,plan_id uuid,applied_plan_version int,
    status text,starts_at_utc timestamptz,ends_at_utc timestamptz,created_at_utc timestamptz);
  CREATE TABLE subscription_plan_publications(plan_id uuid,version int,definition_json jsonb,PRIMARY KEY(plan_id,version));
  CREATE TABLE documents(id int PRIMARY KEY,tenant_id uuid,payload text);
  CREATE TABLE "MixedCase"(id int PRIMARY KEY,"TenantId" uuid,payload text);
  CREATE TABLE adminnotifications(id int PRIMARY KEY,tenant_id uuid,message text);
  CREATE TABLE chats(id uuid PRIMARY KEY,tenant_id uuid);
  CREATE TABLE messages(id uuid PRIMARY KEY,chatid uuid REFERENCES chats(id) ON DELETE CASCADE,content text);
  CREATE TABLE messagereads(messageid uuid REFERENCES messages(id) ON DELETE CASCADE,userid uuid);
  INSERT INTO tenants VALUES('${a}',false),('${b}',false),('${root}',true);
  INSERT INTO documents VALUES(1,'${a}','Existing हिंदी data');
  INSERT INTO subscription_plan_publications VALUES('${plan}',1,'{"StorageLimitGb":0.000001}');
  INSERT INTO tenant_subscriptions VALUES('${plan}','${a}','${plan}',1,'active',now()-interval '1 day',NULL,now());
`);
await db.exec(migration);
const initial = await used();
check(initial > 0, "Existing records must be backfilled");
check(initial === Number(await scalar("SELECT octet_length(convert_to(to_jsonb(d)::text,'UTF8')) FROM documents d WHERE id=1")), "Use UTF-8 bytes, not characters");
await db.exec(migration);
check(await used() === initial, "Migration rerun must not double-count");
check(Number(await scalar("SELECT tenant_storage_limit($1)",[a])) === 1000, "Use applied publication allowance");
check(Number(await scalar("SELECT tenant_storage_limit($1)",[b])) === 10e9, "Fallback allowance");
await db.query('INSERT INTO "MixedCase" VALUES(2,$1,$2)', [a,"hello"]);
const afterInsert = await used();
check(afterInsert > initial, "Mixed-case tenant columns must be metered");
await db.query('UPDATE "MixedCase" SET payload=$1 WHERE id=2', ["a longer payload"]);
check(await used() > afterInsert, "Update growth must be counted");
await db.query('DELETE FROM "MixedCase" WHERE id=2');
check(await used() === initial, "Deletion releases database usage");
await assert.rejects(db.query("INSERT INTO documents VALUES(3,$1,$2)", [a,"x".repeat(1100)]), {code:"P5401"}); checks++;
check(await used() === initial && Number(await scalar("SELECT count(*) FROM documents WHERE id=3")) === 0, "Rejected growth must roll back both row and counter");
await db.query("INSERT INTO documents VALUES(4,$1,$2)", [b,"x".repeat(1100)]);
check(await used() === initial && await used(b) > 1100, "Tenant counters remain isolated");
await assert.rejects(db.query("UPDATE documents SET tenant_id=$1 WHERE id=4", [a]), {code:"P5401"}); checks++;
check(await used(b) > 1100 && await used() === initial, "Rejected ownership transfer rolls back both counters");
await db.query("UPDATE tenant_storage_usage SET file_bytes=11000000000 WHERE tenant_id=$1",[root]);
await db.query("INSERT INTO documents VALUES(5,$1,$2)", [root,"x".repeat(1200)]);
check(await used(root) > 1200, "Root data is measured but exempt");
await db.query("UPDATE tenant_storage_usage SET file_bytes=950 WHERE tenant_id=$1",[a]);
await assert.rejects(db.query("INSERT INTO documents VALUES(6,$1,'small')", [a]), {code:"P5401"}); checks++;
await db.query("UPDATE documents SET payload='' WHERE id=1");
check(await used() < initial, "Shrinking a record is allowed above the combined limit");
await db.query("DELETE FROM documents WHERE id=1");
check(await used() === 0, "Deletion is allowed while over quota");
await db.query("INSERT INTO adminnotifications VALUES(1,$1,$2)", [a,"x".repeat(2000)]);
check(await used() === 0, "Recovery notifications must not consume allowance");
await db.query("UPDATE tenant_storage_usage SET file_bytes=0 WHERE tenant_id=$1",[a]);
await db.query("INSERT INTO chats VALUES($1,$2)",[plan,a]);
await assert.rejects(db.query("INSERT INTO messages(id,chatid,content) VALUES($1,$2,$3)",[plan,plan,"x".repeat(1100)]), {code:"P5401"}); checks++;
await db.query("INSERT INTO messages(id,chatid,content,tenant_id) VALUES($1,$2,'hello',$3)",[plan,plan,b]);
check(await scalar("SELECT tenant_id FROM messages WHERE id=$1",[plan]) === a, "Messages inherit chat ownership, ignoring supplied tenant");
await db.query("INSERT INTO messagereads(messageid,userid) VALUES($1,$2)",[plan,a]);
check(await scalar("SELECT tenant_id FROM messagereads WHERE messageid=$1",[plan]) === a, "Nested children inherit ownership");
const totalWithChildren = await used();
await db.exec(migration);
check(await used() === totalWithChildren, "Child backfill is idempotent");
await db.query("DELETE FROM chats WHERE id=$1",[plan]);
check(await used() === 0, "Cascading deletes release child bytes after the parent is gone");
const service = await readFile(new URL("../../backend/Mahima.Api.v3.clean/services/TenantStorageService.cs", import.meta.url),"utf8");
const reserveSql = service.match(/UPDATE public\.tenant_storage_usage u SET file_bytes=file_bytes\+@bytes[\s\S]*?RETURNING tenant_id/)[0]
  .replaceAll("@id","$1").replaceAll("@bytes","$2");
const reservations = await Promise.all([db.query(reserveSql,[a,600]),db.query(reserveSql,[a,600])]);
check(reservations.reduce((sum,r)=>sum+r.rows.length,0)===1, "Competing reservations cannot both exceed combined allowance");
check(Number(await scalar("SELECT file_bytes FROM tenant_storage_usage WHERE tenant_id=$1",[a]))===600,"Rejected reservation leaves counter unchanged");
await db.query("INSERT INTO subscription_plan_publications VALUES($1,2,$2)",[plan,JSON.stringify({StorageLimitGb:0.000002})]);
check(Number(await scalar("SELECT tenant_storage_limit($1)",[a])) === 1000, "Unaccepted package version does not change allowance");
await db.exec("UPDATE tenant_subscriptions SET applied_plan_version=2");
check(Number(await scalar("SELECT tenant_storage_limit($1)",[a])) === 2000, "Accepted upgrade applies immediately");
await db.exec("UPDATE tenant_subscriptions SET ends_at_utc=now()-interval '1 second'");
check(Number(await scalar("SELECT tenant_storage_limit($1)",[a])) === 10e9, "Expired package loses allowance");
await db.close();
console.log(`PASS: ${checks} tenant storage integration checks`);
