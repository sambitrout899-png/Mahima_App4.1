// Isolated PostgreSQL integration checks; never connects to the application DB.
import { PGlite } from "../../tmp/storage-sql-test/node_modules/@electric-sql/pglite/dist/index.js";
import { readFile } from "node:fs/promises";
import assert from "node:assert/strict";
const db = new PGlite();
const plan = "20000000-0000-0000-0000-000000000001";
const other = "30000000-0000-0000-0000-000000000001";
const source = (id) => `plan:${id.replaceAll("-", "")}`.slice(0,32);
const scalar = async (sql) => Object.values((await db.query(sql)).rows[0])[0];
let checks = 0;
const check = (value, message) => { assert.ok(value,message); checks++; };
await db.exec(`
CREATE TABLE subscription_plans(id uuid PRIMARY KEY,lifecycle_status text,enabled boolean);
CREATE TABLE tenant_subscriptions(id int PRIMARY KEY,plan_id uuid,status text,ends_at_utc timestamptz,updated_at_utc timestamptz);
CREATE TABLE tenant_module_licenses(id int PRIMARY KEY,source text,status text,ends_at_utc timestamptz,updated_at_utc timestamptz);
CREATE TABLE subscription_plan_publications(plan_id uuid,version int,expired_at_utc timestamptz);
CREATE TABLE package_version_upgrade_requests(plan_id uuid,status text,decided_at_utc timestamptz);
CREATE TABLE package_payment_requests(plan_id uuid,status text,review_note text,reviewed_at_utc timestamptz);
INSERT INTO subscription_plans VALUES('${plan}','expired',true),('${other}','published',true);
INSERT INTO tenant_subscriptions(id,plan_id,status) VALUES(1,'${plan}','active'),(2,'${other}','active');
INSERT INTO tenant_module_licenses(id,source,status) VALUES(1,'${source(plan)}','active'),(2,'${source(other)}','active'),(3,'manual','active');
INSERT INTO subscription_plan_publications(plan_id,version) VALUES('${plan}',1),('${plan}',2),('${other}',1);
INSERT INTO package_version_upgrade_requests VALUES('${plan}','pending',NULL);
INSERT INTO package_payment_requests VALUES('${plan}','pending',NULL,NULL);
`);
const sql = await readFile(new URL("../../backend/Mahima.Api.v3.clean/Sql/20260918_expired_package_lifecycle.sql",import.meta.url),"utf8");
await db.exec(sql);
check(await scalar("SELECT status FROM tenant_subscriptions WHERE id=1") === "expired","Previously expired package subscriptions repaired");
check(await scalar("SELECT status FROM tenant_module_licenses WHERE id=1") === "expired","Previously expired package licenses revoked");
check(Number(await scalar(`SELECT count(*) FROM subscription_plan_publications WHERE plan_id='${plan}' AND expired_at_utc IS NULL`)) === 0,"All retired versions expire");
check(await scalar("SELECT status FROM package_version_upgrade_requests") === "cancelled","Pending upgrades cancelled");
check(await scalar("SELECT status FROM package_payment_requests") === "rejected","Pending payments rejected without deleting history");
check(await scalar("SELECT status FROM tenant_subscriptions WHERE id=2") === "active","Other packages remain active");
check(await scalar("SELECT status FROM tenant_module_licenses WHERE id=3") === "active","Independent manual licenses remain active");
await assert.rejects(db.exec("UPDATE tenant_subscriptions SET status='active' WHERE id=1"),{code:"P5403"}); checks++;
await assert.rejects(db.exec("UPDATE tenant_module_licenses SET status='active' WHERE id=1"),{code:"P5403"}); checks++;
await db.exec(`UPDATE subscription_plans SET lifecycle_status='deleted' WHERE id='${plan}'`);
check(Number(await scalar("SELECT count(*) FROM tenant_subscriptions")) === 2,"Deletion preserves subscription history");
await assert.rejects(db.exec(`UPDATE subscription_plans SET lifecycle_status='published',enabled=true WHERE id='${plan}'`),{code:"P5403"}); checks++;
await db.exec(`UPDATE subscription_plans SET lifecycle_status='expired',enabled=false WHERE id='${other}'`);
check(await scalar("SELECT status FROM tenant_subscriptions WHERE id=2") === "expired","New expiry revokes existing subscription");
check(await scalar("SELECT status FROM tenant_module_licenses WHERE id=2") === "expired","New expiry revokes package access");
await db.exec(`UPDATE subscription_plans SET lifecycle_status='draft',enabled=true WHERE id='${other}'`);
await assert.rejects(db.exec("UPDATE tenant_subscriptions SET status='active' WHERE id=2"),{code:"P5403"}); checks++;
await db.exec(`UPDATE subscription_plans SET lifecycle_status='published' WHERE id='${other}'`);
check(await scalar("SELECT status FROM tenant_subscriptions WHERE id=2") === "expired","Republishing does not silently reactivate retired subscriptions");
await db.exec(sql);
check(await scalar("SELECT lifecycle_status FROM subscription_plans WHERE id='"+plan+"'") === "deleted","Migration rerun preserves deletion");
await db.close();
console.log(`PASS: ${checks} package lifecycle integration checks`);
