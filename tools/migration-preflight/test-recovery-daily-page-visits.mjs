import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {PGlite} from '../../tmp/storage-sql-test/node_modules/@electric-sql/pglite/dist/index.js';

const root = '00000000-0000-0000-0000-000000000001';
const strip = s => s.replace(/^\\.*$/gm, '');
const raw = readFileSync('tools/migration-preflight/recovery-rehearse-daily-page-visits.sql', 'utf8');
const runnable = strip(raw);

const cols = `id bigint,user_id uuid,path text NOT NULL,title text,referrer text,user_agent text,ip_address text,
 created_at_utc timestamptz NOT NULL DEFAULT now()`;

// Same shape as the rehearsal-era test (target ids 1..5373, 139 byte-identical collisions,
// 5234 differing collisions, 2610 non-colliding with the extra ids sitting immediately adjacent
// to target's max to exercise the boundary trap) - the specific numbers here are just this
// fixture's choice now, not something the script itself hardcodes or checks against.
async function fixture() {
  const db = new PGlite();
  await db.exec(`CREATE SCHEMA migration_source; CREATE SCHEMA migration_v40;
  CREATE TABLE public.tenants(id uuid PRIMARY KEY, slug text, name text);
  INSERT INTO public.tenants VALUES ('${root}'::uuid,'mahima-root','Mahima Ministry');
  CREATE TABLE public.users(id uuid PRIMARY KEY, tenant_id uuid);
  CREATE TABLE public.daily_page_visits(${cols},tenant_id uuid NOT NULL DEFAULT '${root}'::uuid,PRIMARY KEY(id));
  ALTER TABLE public.daily_page_visits ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  CREATE TABLE migration_source.daily_page_visits(${cols},PRIMARY KEY(id));
  INSERT INTO public.daily_page_visits(id,path,created_at_utc,tenant_id)
   SELECT i,'/path-'||i,'2020-01-01'::timestamptz+(i||' seconds')::interval,'${root}'::uuid FROM generate_series(1,5373) i;
  INSERT INTO migration_source.daily_page_visits(id,path,created_at_utc)
   SELECT i,'/path-'||i,'2020-01-01'::timestamptz+(i||' seconds')::interval FROM generate_series(1,139) i;
  INSERT INTO migration_source.daily_page_visits(id,path,created_at_utc)
   SELECT i,'/different-'||i,'2021-01-01'::timestamptz+(i||' seconds')::interval FROM generate_series(140,5373) i;
  INSERT INTO migration_source.daily_page_visits(id,path,created_at_utc)
   SELECT i,'/source-'||i,'2022-01-01'::timestamptz+(i||' seconds')::interval FROM generate_series(5374,7983) i;
  SELECT setval(pg_get_serial_sequence('public.daily_page_visits','id'),5373,true);`);
  return db;
}

{
  const db = await fixture();
  await db.exec(runnable);

  const total = Number((await db.query('SELECT count(*) n FROM public.daily_page_visits')).rows[0].n);
  assert.equal(total, 13217, '5373 pre-existing + 2610 insert + 5234 remapped, 139 reused not duplicated');
  const distinctIds = Number((await db.query('SELECT count(DISTINCT id) n FROM public.daily_page_visits')).rows[0].n);
  assert.equal(distinctIds, total, 'no duplicate ids landed in the target table');

  const actions = await db.query('SELECT action,count(*) n FROM migration_v40.daily_page_visit_id_map GROUP BY action');
  const byAction = Object.fromEntries(actions.rows.map(r => [r.action, Number(r.n)]));
  assert.deepEqual(byAction, {insert: 2610, reuse_identical: 139, insert_remapped: 5234});

  assert.equal(
    (await db.query('SELECT path FROM public.daily_page_visits WHERE id=1')).rows[0].path,
    '/path-1', 'identical row 1 left exactly as-is, not touched or duplicated');
  assert.equal(
    (await db.query('SELECT path FROM public.daily_page_visits WHERE id=140')).rows[0].path,
    '/path-140', 'pre-existing target row 140 was not overwritten by the differing source row');
  const remapped140 = await db.query("SELECT id FROM public.daily_page_visits WHERE path='/different-140'");
  assert.equal(remapped140.rows.length, 1, 'the differing source row 140 was inserted under a new id');
  assert.notEqual(remapped140.rows[0].id, 140);
  const boundaryRow = await db.query("SELECT id FROM public.daily_page_visits WHERE path='/source-5374'");
  assert.equal(boundaryRow.rows[0].id, 5374, 'the non-colliding row right at the naive boundary kept its own id');

  await assert.rejects(() => db.exec(runnable), /already committed/);
  await db.exec('ROLLBACK');
  await db.close();
  console.log('PASS: 139 identical collisions reused without duplicating, 5234 differing collisions remapped off any id in use, 2610 non-colliding kept their id at the boundary, pre-existing rows untouched, rerun guard, wrong-database guard is schema-shape based.');
}
{
  const db = await fixture();
  await db.exec("INSERT INTO public.users VALUES ('11111111-1111-1111-1111-111111111111','" + root + "'::uuid)");
  await db.exec("UPDATE migration_source.daily_page_visits SET user_id='22222222-2222-2222-2222-222222222222' WHERE id=5374");
  await assert.rejects(() => db.exec(runnable), /user_id that does not exist/);
  await db.exec('ROLLBACK');
  assert.equal((await db.query("SELECT to_regclass('migration_v40.daily_page_visit_id_map') n")).rows[0].n, null);
  await db.close();
  console.log('PASS: a source row referencing an unmigrated user_id aborts and rolls back rather than inserting a dangling reference.');
}
{
  const db = new PGlite();
  await db.exec(`CREATE SCHEMA migration_source; CREATE SCHEMA migration_v40;
  CREATE TABLE public.users(id uuid PRIMARY KEY, tenant_id uuid);
  CREATE TABLE public.daily_page_visits(${cols},tenant_id uuid NOT NULL DEFAULT '${root}'::uuid,PRIMARY KEY(id));
  CREATE TABLE migration_source.daily_page_visits(${cols},PRIMARY KEY(id));`);
  // No public.tenants table at all - this is what a V4.0 database looks like.
  await assert.rejects(() => db.exec(runnable), /Not a multi-tenant \(V4.1\) database/);
  await db.exec('ROLLBACK');
  await db.close();
  console.log('PASS: running against a database with no tenants table (i.e. V4.0 itself) is refused rather than silently writing V4.0-shaped rows into V4.0.');
}
