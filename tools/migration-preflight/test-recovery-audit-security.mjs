// ---------- AuditLogs: 846 identical / 85980 differing / 98328 non-colliding (same fixture shape as before) ----------
{
  const raw = readFileSync('tools/migration-preflight/recovery-rehearse-audit-logs.sql', 'utf8');
  const runnable = strip(raw);

  async function fixture() {
    const db = new PGlite();
    await db.exec(`CREATE SCHEMA migration_source; CREATE SCHEMA migration_v40;
    ${tenantsDdl}
    CREATE TABLE public.users(id uuid PRIMARY KEY, tenant_id uuid);
    CREATE TABLE public."AuditLogs"("Id" bigint,"ActorId" uuid,"Action" text NOT NULL,"EntityType" text,"EntityId" text,
     "Details" text,"CreatedAt" timestamptz NOT NULL,tenant_id uuid NOT NULL,PRIMARY KEY("Id"));
    ALTER TABLE public."AuditLogs" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY;
    CREATE TABLE migration_source."AuditLogs"("Id" bigint,"ActorId" uuid,"Action" text NOT NULL,"EntityType" text,
     "EntityId" text,"Details" text,"CreatedAt" timestamptz NOT NULL,PRIMARY KEY("Id"));
    INSERT INTO public."AuditLogs"("Id","Action","CreatedAt",tenant_id)
     SELECT i,'target-action-'||i,'2020-01-01'::timestamptz+(i||' seconds')::interval,'${root}'::uuid FROM generate_series(1,86854) i;
    INSERT INTO migration_source."AuditLogs"("Id","Action","CreatedAt")
     SELECT i,'target-action-'||i,'2020-01-01'::timestamptz+(i||' seconds')::interval FROM generate_series(1,846) i;
    INSERT INTO migration_source."AuditLogs"("Id","Action","CreatedAt")
     SELECT i,'different-action-'||i,'2021-01-01'::timestamptz+(i||' seconds')::interval FROM generate_series(847,86826) i;
    INSERT INTO migration_source."AuditLogs"("Id","Action","CreatedAt")
     SELECT i,'source-action-'||i,'2022-01-01'::timestamptz+(i||' seconds')::interval FROM generate_series(86855,185182) i;
    SELECT setval(pg_get_serial_sequence('public."AuditLogs"','Id'),86854,true);`);
    return db;
  }

  const db = await fixture();
  await db.exec(runnable);
  const total = Number((await db.query('SELECT count(*) n FROM public."AuditLogs"')).rows[0].n);
  assert.equal(total, 271162, '86854 pre-existing + 98328 insert + 85980 remapped, 846 reused not duplicated');
  const distinctIds = Number((await db.query('SELECT count(DISTINCT "Id") n FROM public."AuditLogs"')).rows[0].n);
  assert.equal(distinctIds, total, 'no duplicate ids landed in the target table');
  const actions = await db.query('SELECT action,count(*) n FROM migration_v40.audit_log_id_map GROUP BY action');
  assert.deepEqual(Object.fromEntries(actions.rows.map(r => [r.action, Number(r.n)])),
    {insert: 98328, reuse_identical: 846, insert_remapped: 85980});
  assert.equal(
    (await db.query('SELECT "Action" a FROM public."AuditLogs" WHERE "Id"=847')).rows[0].a,
    'target-action-847', 'pre-existing target row 847 was not overwritten by the differing source row');
  const boundaryRow = await db.query(`SELECT "Id" FROM public."AuditLogs" WHERE "Action"='source-action-86855'`);
  assert.equal(boundaryRow.rows[0].Id, 86855, 'the non-colliding row right at the naive boundary kept its own id');

  await assert.rejects(() => db.exec(runnable), /already committed/);
  await db.exec('ROLLBACK');
  await db.close();
  console.log('PASS AuditLogs: 846 identical collisions reused, 85980 differing collisions remapped, 98328 non-colliding kept their id including at the boundary, pre-existing rows untouched, rerun guard.');
}
