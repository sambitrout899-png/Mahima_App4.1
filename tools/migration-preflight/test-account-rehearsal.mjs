import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {PGlite} from '../../tmp/storage-sql-test/node_modules/@electric-sql/pglite/dist/index.js';
const raw=readFileSync('tools/migration-preflight/recovery-rehearse-accounts.sql','utf8');
const runnable=raw.replace(/^\\.*$/gm,'');
const root = '00000000-0000-0000-0000-000000000001';
async function fixture() {
 const db=new PGlite();
 await db.exec(`CREATE SCHEMA migration_source; CREATE SCHEMA migration_v40;
 CREATE TABLE public.tenants(id uuid PRIMARY KEY, slug text, name text);
 INSERT INTO public.tenants VALUES ('${root}'::uuid,'mahima-root','Mahima Ministry');
 CREATE TABLE migration_v40.user_code_map(id integer);
 CREATE TABLE public.accounts(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name text NOT NULL,type text NOT NULL,created_at timestamptz NOT NULL,tenant_id uuid NOT NULL);
 CREATE UNIQUE INDEX account_name ON public.accounts(tenant_id,lower(name));
 CREATE TABLE migration_source.accounts(id bigint,name text,type text,created_at timestamptz);
 INSERT INTO migration_source.accounts SELECT i,'Account '||i,'asset','2020-01-01Z'::timestamptz FROM generate_series(1,48) i;
 INSERT INTO public.accounts SELECT i,'Account '||i,'asset','2020-01-01Z'::timestamptz,'${root}'::uuid FROM generate_series(1,31) i;
 INSERT INTO public.accounts SELECT i,'Other '||i,'asset','2020-01-01Z'::timestamptz,'00000000-0000-0000-0000-000000000002'::uuid FROM generate_series(100,155) i;
 SELECT setval(pg_get_serial_sequence('public.accounts','id'),1000,true);`);
 return db;
}
{
 const db=await fixture();
 await db.exec(runnable);
 assert.equal(Number((await db.query('SELECT count(*) n FROM accounts')).rows[0].n),104);
 assert.equal(Number((await db.query("SELECT nextval(pg_get_serial_sequence('public.accounts','id')) n")).rows[0].n),1001);
 assert.equal(Number((await db.query("SELECT count(*) n FROM migration_v40.account_id_map WHERE action='reuse_identical'")).rows[0].n),31);
 await assert.rejects(db.exec(runnable),/already committed/); await db.exec('ROLLBACK');
 await db.close();
 console.log('PASS: 17 inserts/31 reuses, preservation checks, monotonic identity restart and rerun guard.');
}
{
 const db=await fixture();
 await db.exec("UPDATE migration_source.accounts SET type='expense' WHERE id=1");
 await assert.rejects(db.exec(runnable),/Same-name root account differs/); await db.exec('ROLLBACK');
 assert.equal(Number((await db.query('SELECT count(*) n FROM accounts')).rows[0].n),87);
 assert.equal((await db.query("SELECT to_regclass('migration_v40.accounts_before') n")).rows[0].n,null);
 await db.close();
 console.log('PASS: unexpected source/root account difference aborts and rolls back all changes.');
}
{
 const db=new PGlite();
 await db.exec(`CREATE SCHEMA migration_source; CREATE SCHEMA migration_v40;
 CREATE TABLE migration_v40.user_code_map(id integer);
 CREATE TABLE public.accounts(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name text NOT NULL,type text NOT NULL,created_at timestamptz NOT NULL,tenant_id uuid NOT NULL);
 CREATE TABLE migration_source.accounts(id bigint,name text,type text,created_at timestamptz);`);
 // no public.tenants at all - this is what V4.0 itself looks like
 await assert.rejects(db.exec(runnable),/Not a multi-tenant \(V4.1\) database/);
 await db.close();
 console.log('PASS: running against a database with no tenants table is refused.');
}
