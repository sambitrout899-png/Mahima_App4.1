import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {PGlite} from '../../tmp/storage-sql-test/node_modules/@electric-sql/pglite/dist/index.js';
const root='00000000-0000-0000-0000-000000000001',other='00000000-0000-0000-0000-000000000002';
const sql=readFileSync('tools/migration-preflight/recovery-rehearse-prayer-requests.sql','utf8').replace(/^\\.*$/gm,'');
async function fixture(){
 const db=new PGlite();
 await db.exec(`CREATE SCHEMA migration_source; CREATE SCHEMA migration_v40;
 CREATE TABLE public.tenants(id uuid PRIMARY KEY, slug text, name text);
 INSERT INTO public.tenants VALUES ('${root}'::uuid,'mahima-root','Mahima Ministry');
 CREATE TABLE public.prayerrequests(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,userid uuid,title text,
  message text,anonymous boolean,status text,assignedto uuid,createdat timestamptz,createdby text,closecomment text,tenant_id uuid);
 CREATE TABLE migration_source.prayerrequests(id bigint,userid uuid,title text,message text,anonymous boolean,
  status text,assignedto uuid,createdat timestamptz,createdby text,closecomment text);
 INSERT INTO migration_source.prayerrequests SELECT i,'${root}'::uuid,'source-'||i,'msg-'||i,false,'open',NULL,'2026-01-01'::timestamptz+i*interval '1 day','sam',NULL FROM generate_series(1,219)i;
 INSERT INTO public.prayerrequests SELECT i,'${root}'::uuid,'original-'||i,'old',false,'open',NULL,'2025-01-01'::timestamptz,'someone',NULL,CASE WHEN i<=100 THEN '${root}'::uuid ELSE '${other}'::uuid END FROM generate_series(1,120)i;
 SELECT setval(pg_get_serial_sequence('public.prayerrequests','id'),120,true);`);
 return db;
}
{
 const db=await fixture();await db.exec(sql);
 assert.equal(Number((await db.query('SELECT count(*) n FROM public.prayerrequests')).rows[0].n),239,
  '100 pre-existing root rows reused/updated in place + 20 pre-existing other-tenant rows untouched + 119 new inserts (219-100)');
 assert.equal((await db.query("SELECT title t FROM public.prayerrequests WHERE id=1")).rows[0].t,'source-1','id 1 was reused and updated with source content');
 assert.equal((await db.query("SELECT title t FROM public.prayerrequests WHERE id=101")).rows[0].t,'original-101','other-tenant row 101 was left untouched');
 const remapped=await db.query("SELECT id FROM public.prayerrequests WHERE title='source-101'");
 assert.equal(remapped.rows.length,1);
 assert.notEqual(remapped.rows[0].id,101,'source id 101 collided with an other-tenant row and was remapped, not overwriting it');
 await assert.rejects(()=>db.exec(sql),/already committed/);await db.exec('ROLLBACK');await db.close();
 console.log('PASS: root rows reused/updated, other-tenant rows preserved and not overwritten on collision, new rows inserted, rerun guard.');
}
{
 const db=await fixture();
 const broken=sql.replace(' AND t.id=m.target_id','');
 await assert.rejects(()=>db.exec(broken),/reconciliation failed/);
 await db.exec('ROLLBACK');
 assert.equal(Number((await db.query('SELECT count(*) n FROM public.prayerrequests')).rows[0].n),120);
 await db.close();
 console.log('PASS: missing-join defect caught and rolled back.');
}
{
 const db=new PGlite();
 await db.exec('CREATE SCHEMA migration_source; CREATE SCHEMA migration_v40;');
 await assert.rejects(()=>db.exec(sql),/Not a multi-tenant \(V4.1\) database/);
 await db.close();
 console.log('PASS: running against a database with no tenants table is refused.');
}
