import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {PGlite} from '../../tmp/storage-sql-test/node_modules/@electric-sql/pglite/dist/index.js';
const root='00000000-0000-0000-0000-000000000001';
const sql=readFileSync('tools/migration-preflight/recovery-rehearse-prayer-children.sql','utf8').replace(/^\\.*$/gm,'');

async function fixture() {
  const db = new PGlite();
  await db.exec(`CREATE SCHEMA migration_source; CREATE SCHEMA migration_v40;
  CREATE TABLE public.tenants(id uuid PRIMARY KEY, slug text, name text);
  INSERT INTO public.tenants VALUES ('${root}'::uuid,'mahima-root','Mahima Ministry');
  CREATE TABLE public.prayerrequests(id bigint PRIMARY KEY);
  CREATE TABLE public.prayerresponses(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prayerrequestid bigint,userid uuid,message text,author text,createdat timestamptz,updatedat timestamptz);
  CREATE TABLE public.prayertestimonies(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prayerrequestid bigint UNIQUE,userid uuid,title text,testimonytext text,testimonytexthindi text,
    imageurl text,voiceurl text,createdat timestamptz,updatedat timestamptz);
  CREATE TABLE migration_source.prayerresponses(id bigint,prayerrequestid bigint,userid uuid,message text,
    author text,createdat timestamptz,updatedat timestamptz);
  CREATE TABLE migration_source.prayertestimonies(id bigint,prayerrequestid bigint,userid uuid,title text,
    testimonytext text,testimonytexthindi text,imageurl text,voiceurl text,createdat timestamptz,updatedat timestamptz);
  -- prayer_request_id_map: source request ids 1..5 mapped onto target ids 101..105 (already migrated
  -- by the prior stage); source id 999 is NOT in the map at all - its testimony is an orphan.
  CREATE TABLE migration_v40.prayer_request_id_map(source_id bigint PRIMARY KEY,target_id bigint,action text);
  INSERT INTO migration_v40.prayer_request_id_map SELECT i,100+i,'insert_remapped' FROM generate_series(1,5)i;
  INSERT INTO public.prayerrequests SELECT 100+i FROM generate_series(1,5)i;
  INSERT INTO migration_source.prayerresponses SELECT i,((i-1)%5)+1,'${root}'::uuid,'msg-'||i,'author','2026-01-01','2026-01-01' FROM generate_series(1,20)i;
  INSERT INTO migration_source.prayertestimonies SELECT i,i,'${root}'::uuid,'title-'||i,'text-'||i,NULL,NULL,NULL,'2026-01-01','2026-01-01' FROM generate_series(1,5)i;
  INSERT INTO migration_source.prayertestimonies VALUES (999,999,'${root}'::uuid,'orphan title','orphan text',NULL,NULL,NULL,'2026-01-01','2026-01-01');`);
  return db;
}

{
  const db = await fixture();
  await db.exec(sql);
  assert.equal(Number((await db.query('SELECT count(*) n FROM public.prayerresponses')).rows[0].n), 20);
  assert.equal(Number((await db.query('SELECT count(*) n FROM public.prayertestimonies')).rows[0].n), 5);
  assert.equal(Number((await db.query('SELECT count(*) n FROM migration_v40.orphan_prayer_testimonies')).rows[0].n), 1);
  assert.equal((await db.query('SELECT prayerrequestid FROM public.prayerresponses ORDER BY id LIMIT 1')).rows[0].prayerrequestid, 101,
    'response for source request 1 correctly points at remapped target request 101');
  assert.equal((await db.query('SELECT title FROM public.prayertestimonies WHERE prayerrequestid=101')).rows[0].title, 'title-1');

  await assert.rejects(() => db.exec(sql), /already committed/);
  await db.exec('ROLLBACK');
  await db.close();
  console.log('PASS: responses/testimonies remapped onto migrated prayer requests, orphaned testimony archived not inserted, rerun guard.');
}
