import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {PGlite} from '../../tmp/storage-sql-test/node_modules/@electric-sql/pglite/dist/index.js';

const root = '00000000-0000-0000-0000-000000000001';
const strip = s => s.replace(/^\\.*$/gm, '');
const tenantsDdl = `CREATE TABLE public.tenants(id uuid PRIMARY KEY, slug text, name text);
INSERT INTO public.tenants VALUES ('${root}'::uuid,'mahima-root','Mahima Ministry');`;
const baptismsRaw = readFileSync('tools/migration-preflight/recovery-rehearse-baptisms.sql', 'utf8');
const baptismsRunnable = strip(baptismsRaw);
const attachmentsRaw = readFileSync('tools/migration-preflight/recovery-rehearse-attachments.sql', 'utf8');
const attachmentsRunnable = strip(attachmentsRaw);

const baptismCols = `id integer,token text,full_name text NOT NULL,father_name text,mother_name text,date_of_birth timestamptz,
 contact_number text,email text,address text,church_member_id integer,preferred_date timestamptz,preferred_service text,
 church_verified boolean NOT NULL,church_verified_by integer,church_verified_at timestamptz,consent_signed boolean NOT NULL,
 consent_signed_at timestamptz,consent_signed_by integer,status text NOT NULL DEFAULT 'Pending',certificate_pdf_url text,
 baptism_date timestamptz,baptism_place text,baptized_by_user_id integer,created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()`;

async function fixture() {
  const db = new PGlite();
  await db.exec(`CREATE SCHEMA migration_source; CREATE SCHEMA migration_v40;
  ${tenantsDdl}
  CREATE TABLE public.baptism_requests(${baptismCols},tenant_id uuid NOT NULL,PRIMARY KEY(id));
  ALTER TABLE public.baptism_requests ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  CREATE TABLE migration_source.baptism_requests(${baptismCols},PRIMARY KEY(id));
  CREATE TABLE public."Attachments"("Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"OwnerType" text NOT NULL,
   "OwnerId" bigint NOT NULL,"S3Key" text NOT NULL,"Filename" text,"ContentType" text,"SizeBytes" bigint,"UploadedBy" uuid,
   "UploadedAt" timestamptz NOT NULL,"TenantId" uuid NOT NULL);
  CREATE TABLE migration_source."Attachments"("Id" bigint,"OwnerType" text,"OwnerId" bigint,"S3Key" text,"Filename" text,
   "ContentType" text,"SizeBytes" bigint,"UploadedBy" uuid,"UploadedAt" timestamptz);
  -- one colliding root baptism (id 9, different person) plus nine unrelated existing rows
  INSERT INTO public.baptism_requests(id,full_name,church_verified,consent_signed,status,tenant_id)
   SELECT i, CASE WHEN i=9 THEN 'Sambit Rout' ELSE 'Existing '||i END, true, true, 'Completed', '${root}'::uuid
   FROM generate_series(1,10) i;
  INSERT INTO migration_source.baptism_requests(id,full_name,church_verified,consent_signed,status)
   VALUES (9,'Mahindra Pal',true,true,'Completed');
  INSERT INTO migration_source."Attachments"("Id","OwnerType","OwnerId","S3Key","UploadedAt")
   SELECT i,'baptism-signed-certificate',9,'certs/'||i||'.pdf',now() FROM generate_series(1,3) i;
  SELECT setval(pg_get_serial_sequence('public.baptism_requests','id'),10,true);`);
  return db;
}

{
  const db = await fixture();
  await db.exec(baptismsRunnable);
  const map = await db.query("SELECT source_id,target_id,action FROM migration_v40.baptism_id_map");
  assert.equal(map.rows.length, 1);
  assert.equal(map.rows[0].action, 'insert_remapped');
  assert.notEqual(map.rows[0].target_id, 9);
  const newId = map.rows[0].target_id;
  assert.equal(Number((await db.query('SELECT count(*) n FROM public.baptism_requests')).rows[0].n), 11);
  assert.equal((await db.query('SELECT full_name f FROM public.baptism_requests WHERE id=9')).rows[0].f, 'Sambit Rout');
  assert.equal((await db.query(`SELECT full_name f FROM public.baptism_requests WHERE id=${newId}`)).rows[0].f, 'Mahindra Pal');

  await db.exec(attachmentsRunnable);
  const attachments = await db.query('SELECT "Id","OwnerId","TenantId" FROM public."Attachments" ORDER BY "Id"');
  assert.equal(attachments.rows.length, 3);
  for (const row of attachments.rows) {
    assert.equal(row.OwnerId, newId);
    assert.equal(row.TenantId, root);
  }

  await assert.rejects(() => db.exec(baptismsRunnable), /already committed/);
  await db.exec('ROLLBACK');
  await assert.rejects(() => db.exec(attachmentsRunnable), /already committed/);
  await db.exec('ROLLBACK');
  await db.close();
  console.log('PASS: baptism ID remap on collision, attachment OwnerId follows the remap, tenant assignment, rerun guards.');
}
{
  const db = await fixture();
  await db.exec("UPDATE public.baptism_requests SET full_name='Mahindra Pal' WHERE id=9");
  await db.exec(baptismsRunnable);
  const map = await db.query("SELECT source_id,target_id,action FROM migration_v40.baptism_id_map");
  assert.equal(map.rows[0].action, 'reuse_identical', 'an accidentally-identical collision is reused, not treated as an error');
  assert.equal(map.rows[0].target_id, 9);
  assert.equal(Number((await db.query('SELECT count(*) n FROM public.baptism_requests')).rows[0].n), 10,
    'no new row inserted for the identical collision');
  await db.close();
  console.log('PASS: an accidentally-identical colliding record is reused (not duplicated, not an error) rather than the old hard-abort behavior.');
}
{
  const db = await fixture();
  await db.exec("UPDATE migration_source.\"Attachments\" SET \"OwnerType\"='sermon-audio' WHERE \"Id\"=1");
  await db.exec(baptismsRunnable);
  await assert.rejects(() => db.exec(attachmentsRunnable), /Unreviewed OwnerType present/);
  await db.exec('ROLLBACK');
  await db.close();
  console.log('PASS: an OwnerType this script was never reviewed against aborts instead of silently mis-copying it.');
}
{
  const db = new PGlite();
  await db.exec(`CREATE SCHEMA migration_source; CREATE SCHEMA migration_v40;
  CREATE TABLE public.baptism_requests(${baptismCols},tenant_id uuid NOT NULL,PRIMARY KEY(id));
  CREATE TABLE migration_source.baptism_requests(${baptismCols},PRIMARY KEY(id));`);
  await assert.rejects(() => db.exec(baptismsRunnable), /Not a multi-tenant \(V4.1\) database/);
  await db.close();
  console.log('PASS: baptisms - running against a database with no tenants table is refused.');
}
