-- Worship / service planning: an ordered run-sheet of items (songs, sermon, prayer,
-- announcements, offering, etc.) per service date, each optionally assigned to a volunteer.
CREATE TABLE IF NOT EXISTS public.service_plans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    title varchar(200) NOT NULL,
    service_date date NOT NULL,
    sermon_id bigint NULL,
    notes text NULL,
    created_by_user_id uuid NULL,
    created_at_utc timestamptz NOT NULL DEFAULT now(),
    updated_at_utc timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_service_plans_tenant_date ON public.service_plans (tenant_id, service_date);

CREATE TABLE IF NOT EXISTS public.service_plan_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    service_plan_id bigint NOT NULL REFERENCES public.service_plans(id) ON DELETE CASCADE,
    order_index integer NOT NULL DEFAULT 0,
    item_type varchar(30) NOT NULL DEFAULT 'song', -- song | announcement | sermon | prayer | offering | other
    title varchar(200) NOT NULL,
    details text NULL,
    assigned_user_id uuid NULL,
    duration_minutes integer NULL
);
CREATE INDEX IF NOT EXISTS ix_service_plan_items_plan ON public.service_plan_items (service_plan_id, order_index);
