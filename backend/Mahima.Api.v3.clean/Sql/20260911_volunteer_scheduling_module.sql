-- Volunteer scheduling: shifts (tied optionally to a Team/Position/Event) with self-signup.
CREATE TABLE IF NOT EXISTS public.volunteer_shifts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    title varchar(200) NOT NULL,
    notes text NULL,
    team_id bigint NULL,
    event_id bigint NULL REFERENCES public.events(id) ON DELETE SET NULL,
    shift_date date NOT NULL,
    start_time time NULL,
    end_time time NULL,
    slots_needed integer NOT NULL DEFAULT 1,
    created_by_user_id uuid NULL,
    created_at_utc timestamptz NOT NULL DEFAULT now(),
    updated_at_utc timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_volunteer_shifts_tenant_date ON public.volunteer_shifts (tenant_id, shift_date);

CREATE TABLE IF NOT EXISTS public.volunteer_signups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    shift_id bigint NOT NULL REFERENCES public.volunteer_shifts(id) ON DELETE CASCADE,
    user_id uuid NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'signed_up', -- signed_up | confirmed | cancelled
    signed_up_at_utc timestamptz NOT NULL DEFAULT now(),
    reminder_sent_at_utc timestamptz NULL
);
CREATE INDEX IF NOT EXISTS ix_volunteer_signups_shift ON public.volunteer_signups (shift_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS ux_volunteer_signups_user_shift ON public.volunteer_signups (shift_id, user_id) WHERE status <> 'cancelled';
