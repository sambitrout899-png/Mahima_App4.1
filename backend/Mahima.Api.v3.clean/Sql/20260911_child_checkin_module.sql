-- Child check-in / kids-ministry security. Guardian-linked check-in and check-out with a
-- generated matching security code (printed on both the child's tag and guardian's claim
-- ticket via the existing tenant print-template pipeline).
CREATE TABLE IF NOT EXISTS public.child_checkins (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    event_id bigint NULL REFERENCES public.events(id) ON DELETE SET NULL,
    child_name varchar(160) NOT NULL,
    child_dob date NULL,
    guardian_name varchar(160) NOT NULL,
    guardian_phone varchar(32) NULL,
    guardian_user_id uuid NULL,
    security_code varchar(12) NOT NULL,
    allergy_notes text NULL,
    general_notes text NULL,
    checked_in_at_utc timestamptz NOT NULL DEFAULT now(),
    checked_in_by_user_id uuid NULL,
    checked_out_at_utc timestamptz NULL,
    checked_out_by_user_id uuid NULL
);
CREATE INDEX IF NOT EXISTS ix_child_checkins_tenant_open ON public.child_checkins (tenant_id, checked_out_at_utc);
CREATE INDEX IF NOT EXISTS ix_child_checkins_event ON public.child_checkins (event_id);
CREATE INDEX IF NOT EXISTS ix_child_checkins_security_code ON public.child_checkins (tenant_id, security_code);
