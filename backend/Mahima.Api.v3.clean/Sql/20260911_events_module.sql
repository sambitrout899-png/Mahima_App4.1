-- Public Events module: church events with optional RSVP/capacity, separate from the
-- lightweight internal "Meetings" table. Public-facing events surface on the tenant's
-- landing/member portal; private events are staff/admin-only.
CREATE TABLE IF NOT EXISTS public.events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    title varchar(200) NOT NULL,
    description text NULL,
    category varchar(60) NULL,
    location text NULL,
    cover_image_url text NULL,
    start_at_utc timestamptz NOT NULL,
    end_at_utc timestamptz NULL,
    is_public boolean NOT NULL DEFAULT true,
    requires_rsvp boolean NOT NULL DEFAULT false,
    capacity integer NULL,
    status varchar(20) NOT NULL DEFAULT 'scheduled', -- scheduled | cancelled | completed
    created_by_user_id uuid NULL,
    created_at_utc timestamptz NOT NULL DEFAULT now(),
    updated_at_utc timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_events_tenant_start ON public.events (tenant_id, start_at_utc);
CREATE INDEX IF NOT EXISTS ix_events_tenant_public ON public.events (tenant_id, is_public, start_at_utc);

CREATE TABLE IF NOT EXISTS public.event_rsvps (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    user_id uuid NULL, -- null for guest RSVPs
    guest_name varchar(160) NULL,
    guest_contact varchar(160) NULL,
    party_size integer NOT NULL DEFAULT 1,
    status varchar(20) NOT NULL DEFAULT 'confirmed', -- confirmed | waitlisted | cancelled
    created_at_utc timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_event_rsvps_has_identity CHECK (user_id IS NOT NULL OR guest_name IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS ix_event_rsvps_event ON public.event_rsvps (event_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS ux_event_rsvps_user_event ON public.event_rsvps (event_id, user_id) WHERE user_id IS NOT NULL;
