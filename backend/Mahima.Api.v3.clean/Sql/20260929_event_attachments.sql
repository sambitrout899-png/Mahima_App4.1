-- Files (images, documents, video clips, etc.) attached to an event. The actual bytes
-- are stored via the existing /api/uploads pipeline (UploadsController); this table only
-- records the resulting link against the event.
CREATE TABLE IF NOT EXISTS public.event_attachments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
    event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    file_name varchar(260) NOT NULL,
    file_url text NOT NULL,
    content_type varchar(120) NOT NULL,
    file_size_bytes bigint NULL,
    uploaded_by_user_id uuid NULL,
    created_at_utc timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_event_attachments_event ON public.event_attachments (event_id);
